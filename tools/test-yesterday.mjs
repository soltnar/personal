import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../script.js',import.meta.url),'utf8');
const context=vm.createContext({sabyFromInput:{value:''},sabyToInput:{value:''}});
vm.runInContext(source.slice(source.indexOf('function yesterdayMoscow('),source.indexOf('function excelDateToSerialDay(')),context);
for(const [now,expected] of [['2026-10-22T08:00:00Z','2026-10-21'],['2026-10-21T21:01:00Z','2026-10-21'],['2026-01-01T00:00:00Z','2025-12-31'],['2024-03-01T00:00:00Z','2024-02-29']])assert.equal(context.yesterdayMoscow(new Date(now)),expected);
context.setDefaultSabyPeriod(new Date('2026-10-23T08:00:00Z'));
assert.equal(context.sabyFromInput.value,'2026-10-22');assert.equal(context.sabyToInput.value,'2026-10-22');
context.sabyFromInput.value='2026-10-01';context.sabyToInput.value='2026-10-15';context.setDefaultSabyPeriod();
assert.equal(context.sabyFromInput.value,'2026-10-01');assert.equal(context.sabyToInput.value,'2026-10-15');
console.log('PASS: yesterday default for both inputs, Moscow midnight, year boundary, leap day, explicit period preserved');
